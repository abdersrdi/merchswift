import CutLine
import DocumentModel
import Foundation

public extension Preflight {
    /// Applies a fix to the document. Returns false when the fix could not be applied (the layer is gone, or the fix
    /// needs a tool that is not available yet). Pass a shaper so text is laid out again after its size changes.
    @discardableResult
    static func apply(_ fix: PreflightFix, to doc: inout Document, shaper: TextShaping? = nil) -> Bool {
        switch fix {
        case .upscaleImage:
            return false            // needs the on-device upscaler

        case .move(let id, let dx, let dy):
            guard doc.layer(id: id) != nil else { return false }
            doc.translate([id], by: [Point(dx, dy)])
            return true

        case .extendToBleed(let id):
            guard let b = doc.worldBounds(of: id) else { return false }
            let canvas = doc.canvas
            let target = b.union(canvas)
            return doc.setFrame(of: id, to: target)

        case .thickenStroke(let id, let width):
            return doc.update(id: id) { layer in
                switch layer.content {
                case .shape(var s): s.stroke?.width = width; layer.content = .shape(s)
                case .text(var t): t.style.stroke?.width = width; layer.content = .text(t)
                default: break
                }
            }

        case .enlargeText(let id, let size):
            let ok = doc.update(id: id) { layer in
                guard case .text(var t) = layer.content else { return }
                t.style.size = size
                if let shaper { t.reshape(using: shaper) }
                layer.content = .text(t)
            }
            return ok

        case .removeTransparency(let id):
            return doc.update(id: id) { layer in
                layer.opacity = 1
                layer.blendMode = .normal
                switch layer.content {
                case .shape(var s):
                    s.fill?.a = 1
                    s.stroke?.color.a = 1
                    layer.content = .shape(s)
                case .text(var t):
                    t.style.fill.a = 1
                    t.style.stroke?.color.a = 1
                    layer.content = .text(t)
                default: break
                }
            }

        case .replaceColor(let id, let target, let color):
            return doc.update(id: id) { layer in
                switch layer.content {
                case .shape(var s):
                    if target == .fill { s.fill = color } else { s.stroke?.color = color }
                    layer.content = .shape(s)
                case .text(var t):
                    if target == .fill { t.style.fill = color } else { t.style.stroke?.color = color }
                    layer.content = .text(t)
                default: break
                }
            }

        case .setCutOffset(let offset):
            var c = doc.cutLine ?? CutLineSettings()
            c.offset = offset
            doc.cutLine = c
            return true

        case .simplifyCutLine:
            var c = doc.cutLine ?? CutLineSettings()
            c.smoothing = max(c.smoothing * 2, 1.5)
            doc.cutLine = c
            return true
        }
    }

    /// Applies every fix that can be applied and runs the checks again. Fixes that change the cut line need the
    /// cut line regenerated by the caller, so `cutPath` is used as given.
    static func fixAll(_ doc: inout Document, preset: ProductPreset? = nil, cutPath: CutPath? = nil,
                       gamut: GamutChecking? = nil, shaper: TextShaping? = nil) -> PreflightReport {
        for _ in 0..<3 {
            let report = run(doc, preset: preset, cutPath: cutPath, gamut: gamut)
            var applied = false
            for issue in report.issues {
                if let fix = issue.fix, apply(fix, to: &doc, shaper: shaper) { applied = true }
            }
            if !applied { break }
        }
        return run(doc, preset: preset, cutPath: cutPath, gamut: gamut)
    }
}
